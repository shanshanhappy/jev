def main():
    with SRC.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        assert reader.fieldnames == FIELDS, f"字段不匹配: {reader.fieldnames}"
        rows = list(reader)
    assert len(rows) == 638, f"标签数不是638: {len(rows)}"

    index = {row["标签ID"]: i for i, row in enumerate(rows)}
    targets = [row["标签ID"] for row in rows[40:60]]
    assert set(FILL) == set(targets), f"填充ID与第41-60个不一致: {set(FILL) ^ set(targets)}"

    for tid, values in FILL.items():
        row = rows[index[tid]]
        keep = (row["标签ID"], row["标签名"], row["现有常见表达"])
        for key, value in values.items():
            assert key in FIELDS, f"未知字段: {key}"
            row[key] = value
        assert keep == (row["标签ID"], row["标签名"], row["现有常见表达"])

    with OUT_CSV.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)

    OUT_JSON.write_text(
        json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    review = [rows[index[t]]["标签ID"] + " " + rows[index[t]]["标签名"]
              for t in targets if rows[index[t]]["是否需人工复核"] == "是"]
    print(f"总标签数: {len(rows)}，本批填写: {len(targets)}（{targets[0]} ~ {targets[-1]}）")
    print(f"累计已填写: {sum(1 for r in rows if r['标签定义'])}")
    print(f"本批标记人工复核 {len(review)} 个: {'; '.join(review)}")
    print(f"输出: {OUT_CSV}")
    print(f"输出: {OUT_JSON}")


if __name__ == "__main__":
    main()
